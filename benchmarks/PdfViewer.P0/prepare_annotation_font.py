"""Prepare the redistributable P0 font from an already licensed Noto CJK TTC.

Only a prototype fixture tool; this is not a product runtime dependency.
Usage: python prepare_annotation_font.py INPUT.ttc OUTPUT_DIRECTORY COPYRIGHT
Requires fontTools. The canonical source and generated bytes are hashed.
"""
import hashlib
import json
from pathlib import Path
import shutil
import sys

from fontTools import subset
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import TTFont

source, output, copyright_file = map(Path, sys.argv[1:4])
output.mkdir(parents=True, exist_ok=True)
font = TTFont(source, fontNumber=2, recalcTimestamp=False)
assert font["name"].getDebugName(1) == "Noto Sans CJK SC"
assert font["OS/2"].fsType == 0, "Embedding is restricted"
text = "中文批注字体验证保存编辑后ABC 123 - Noto P0"
subsetter = subset.Subsetter(options=subset.Options())
subsetter.populate(text=text)
subsetter.subset(font)
# Do not use a reserved upstream family name for the modified font.
family = "P0 Annotation CJK"
for record in font["name"].names:
    if record.nameID in (1, 2, 3, 4, 6):
        replacement = "Regular" if record.nameID == 2 else family.replace(" ", "") if record.nameID == 6 else family
        record.string = replacement.encode(record.getEncoding(), errors="replace")
if "CFF " in font:
    top = font["CFF "].cff.topDictIndex[0]
    top.FamilyName = family
    top.FullName = family
    font["CFF "].cff.fontNames = [family.replace(" ", "")]
# PDFium's Type1 LoadFont route serializes an OpenType/CFF buffer under
# /FontFile, causing Poppler's 'Mismatch between font type and embedded font
# file' warning. Convert the tiny fixture subset to actual TrueType outlines,
# then use FPDF_FONT_TRUETYPE. The converted font has a new family name.
glyph_set = font.getGlyphSet()
glyphs = {}
for name in font.getGlyphOrder():
    target_pen = TTGlyphPen(None)
    glyph_set[name].draw(Cu2QuPen(target_pen, max_err=1.0, reverse_direction=True))
    glyphs[name] = target_pen.glyph()
builder = FontBuilder(font["head"].unitsPerEm, isTTF=True)
builder.setupGlyphOrder(font.getGlyphOrder())
builder.setupCharacterMap(font.getBestCmap())
builder.setupGlyf(glyphs)
builder.setupHorizontalMetrics(font["hmtx"].metrics)
builder.setupHorizontalHeader(ascent=font["hhea"].ascent, descent=font["hhea"].descent)
builder.setupNameTable({"familyName": family, "styleName": "Regular", "uniqueFontIdentifier": family,
                        "fullName": family, "psName": family.replace(" ", ""),
                        "version": "Version 1.000; P0 fixture derivative"})
builder.setupOS2(sTypoAscender=font["OS/2"].sTypoAscender, sTypoDescender=font["OS/2"].sTypoDescender,
                 usWinAscent=font["OS/2"].usWinAscent, usWinDescent=font["OS/2"].usWinDescent, fsType=0)
builder.setupPost()
builder.setupMaxp()
builder.font.recalcTimestamp = False
builder.font["head"].created = builder.font["head"].modified = 3_600_000_000
target = output / "P0AnnotationCjk.ttf"
builder.save(target)
shutil.copyfile(copyright_file, output / "Noto-CJK-COPYRIGHT.txt")
def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()
(output / "font-manifest.json").write_text(json.dumps({
    "source": str(source.resolve()), "sourceSha256": sha(source),
    "sourceFontIndex": 2, "sourceFamily": "Noto Sans CJK SC",
    "embeddingFsType": 0, "license": "SIL Open Font License 1.1; see Noto-CJK-COPYRIGHT.txt",
    "derivedFamily": family, "subsetText": text, "format": "TrueType (converted from CFF subset; quadratic error <= 1 font unit)",
    "generated": str(target.resolve()), "generatedSha256": sha(target),
    "generatedBytes": target.stat().st_size,
    "notice": "Prototype preparation only; production needs a licensed, versioned font source and native font subsetting strategy."
}, ensure_ascii=False, indent=2), encoding="utf-8")
print(target)
