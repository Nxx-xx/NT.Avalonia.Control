"""Export a compact, versionable verification record from completed P0 evidence."""
import argparse
import datetime as dt
import hashlib
import json
import platform
import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path
import pypdf
import cryptography


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--run", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--openssl", required=True)
    parser.add_argument("--poppler", required=True)
    args = parser.parse_args()
    run = Path(args.run).resolve()
    read = lambda path: json.loads((run / path).read_text(encoding="utf-8-sig"))
    sha = lambda path: hashlib.sha256(path.read_bytes()).hexdigest().upper()
    independent, audit, completed = read("independent-verification.json"), read("redaction/independent-audit.json"), read("p0-run.json")
    assert independent["passed"] and audit["Status"] == "expected-restricted-results-confirmed"
    assert completed["Status"] == "experiments-verified-with-open-release-gates"
    regression = []
    for suite in ["Core", "Headless"]:
        xml = ET.parse(run / f"logs/regression-{suite}.xml").getroot()
        assembly = xml.find("assembly")
        assert assembly is not None and assembly.get("failed") == "0" and assembly.get("errors") == "0"
        regression.append({"suite": suite, **{key: assembly.get(key) for key in ["total", "passed", "failed", "errors", "skipped", "time"]}, "xmlSHA256": sha(run / f"logs/regression-{suite}.xml")})
    signatures = read("save/crypto/result.json")
    baseline = read("baseline/baseline.json")
    corpus_paths = ["baseline/reading-2.pdf", "baseline/text-1000.pdf", "save/input.pdf", "save/encrypted-input.pdf", "fixtures/signed-input.pdf", "forms/forms-input.pdf", "fonts/native-stamp-cjk.pdf"]
    corpus_paths += [str(p.relative_to(run)).replace("\\", "/") for p in sorted((run / "redaction").glob("*.input.pdf"))]
    corpus = [{"path": name, "bytes": (run / name).stat().st_size, "sha256": sha(run / name), "source": "Synthetic fixture generated by repository P0 code; no user document data", "scope": "Research/replay only; not representative production corpus"} for name in corpus_paths]
    required = ["baseline/baseline.json", "baseline/source-manifest.json", "baseline/source-snapshot.zip", "baseline/native-assets.json", "baseline/targets.json", "baseline/official-documents/manifest.json", "execution-manifest.json", "save/result.json", "save/crypto/result.json", "fonts/result.json", "fonts/bridge-result.json", "forms/result.json", "redaction/result.json", "redaction/independent-audit.json", "baseline/result.json", "baseline/timing-summary.json", "independent-verification.json", "p0-run.json"]
    for optional in ["baseline-guard-results.json", "redaction/negative-control-results.json", "redaction/visual-review.json", "fonts/render-verification.json"]:
        if (run / optional).exists(): required.append(optional)
    native = read("baseline/native-assets.json")
    result = {
        "schemaVersion": 1, "date": completed["CompletedUtc"][:10], "runId": run.name,
        "exportedUtc": dt.datetime.now(dt.timezone.utc).isoformat(),
        "exporterSHA256": sha(Path(__file__)),
        "status": "P0 feasibility experiments verified; G0 remains open",
        "G0Complete": False, "productEditingReady": False,
        "baseline": {key: baseline.get(key) for key in ["CapturedUtc", "GitCommit", "SDK", "OS", "ProcessArchitecture", "Processor", "LogicalProcessorCount", "SourceFileCount", "SourceManifestSHA256", "SnapshotSHA256"]},
        "frozenProductSourceUnchanged": next(x["passed"] for x in independent["checks"] if x["id"] == "baseline-product-source-unchanged"),
        "executionAssemblySHA256": read("execution-manifest.json")["AssemblySHA256"],
        "native": native,
        "officialDocuments": read("baseline/official-documents/manifest.json"),
        "officialRuntime": {"package": "Avalonia.Controls.PdfViewer", "version": None, "status": "licensed-runnable-reference-not-available"},
        "tools": {"python": platform.python_version(), "pypdf": pypdf.__version__, "cryptography": cryptography.__version__,
            "openssl": subprocess.run([args.openssl, "version"], capture_output=True, text=True, check=True).stdout.strip(),
            "poppler": subprocess.run([args.poppler, "-v"], capture_output=True, text=True, check=True).stderr.splitlines()[0]},
        "independentChecks": {"passed": sum(x["passed"] for x in independent["checks"]), "total": len(independent["checks"]), "ids": [x["id"] for x in independent["checks"]]},
        "save": {"status": "limited-feasible", "checks": read("save/result.json")["Result"]["Checks"],
            "signatures": [{key: x[key] for key in ["crypto_integrity", "expected_integrity", "signed_revision_length", "file_length", "covers_latest_revision", "openssl_exit", "trust_and_DocMDP"]} | {"file": Path(x["file"]).name} for x in signatures]},
        "fonts": {"status": "limited-feasible", "nativeStamp": "embedded CJK AP, reopen/edit/save validated", "freeTextNative": "AppendObject unsupported; SetAP cannot by itself provide the embedded font resource", "freeTextBridge": "pypdf resource-preserving writer experiment passed; no production writer implemented", "fixture": json.loads((run / "fonts/font-provenance.json").read_text())},
        "forms": {"status": "limited-feasible", "checks": read("forms/result.json")["Result"]["Checks"], "routing": "keydown Return alone did not commit combobox; OnChar(Return) required", "scope": "ASCII text, checkbox, non-editable combobox; no OS IME/UI claim"},
        "redaction": {"status": "restricted-primitives-only; general-redaction-blocked", "cases": [{key: c[key] for key in ["Name", "Classification", "ExpectedResultObserved"]} for c in audit["Cases"]], "hiddenStructuralBridgePassed": audit["StructuralBridge"]["Passed"], "scope": "Synthetic text/image/whole-exclusive-Form object deletion verified. Hidden/native and nested/shared Form child-edit counterexamples confirmed; partial text/image explicitly refused. Python bridge only proves a restricted fresh-catalog cleanup route."},
        "backendTiming": read("baseline/timing-summary.json"), "regression": regression,
        "corpus": corpus,
        "openG0Items": ["Commercial reference package/version and actual official performance comparison", "Ubuntu 24.04 x64 native desktop evidence and exact environment", "Kylin x64/ARM64 exact images, devices and physical acceptance", "Representative production-size/scanned/vector/shaping corpus and UI performance protocol calibration", "Production FreeText/font-resource/subsetting writer choice", "Character-level redaction, shared/nested object rewrite and complete hidden-data sanitizer proof"],
        "evidence": [{"path": name, "sha256": sha(run / name), "bytes": (run / name).stat().st_size} for name in required],
    }
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(output)


if __name__ == "__main__":
    main()
